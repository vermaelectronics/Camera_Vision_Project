#!/usr/bin/env python3
"""
Generates rtl/mesprit_asin_lut.v (arcsin ROM used by the DAR stage).

Table layout (input |u| in Q1.30, output radians in Q2.28 = Q28):
  * coarse : 1025 points over [0, 1]                 (1024 segments)
  * fine   : 1025 points over [1 - 1/32, 1]           (1024 segments)
The fine table keeps the linear-interpolation error below 0.12 deg even at
end-fire (|u| -> 1, where d(asin)/du -> inf). For |u| < 0.99 the error is
below 0.0005 deg.

Run:  python3 gen_luts.py ../rtl/mesprit_asin_lut.v
"""
import math
import sys

N = 1024
FINE_START = 1.0 - 1.0 / 32.0
Q = 1 << 28


def table(x0, x1):
    return [int(round(math.asin(min(1.0, x0 + (x1 - x0) * k / N)) * Q)) for k in range(N + 1)]


def main(path):
    coarse = table(0.0, 1.0)
    fine = table(FINE_START, 1.0)
    # 2048 x 30 ROM: coarse[0..1022] at 0..1022 (only 0..992 are reachable,
    # because |u| >= 1-1/32 uses the fine table), fine[0..1024] at 1023..2047
    rom = coarse[:1023] + fine
    assert len(rom) == 2048
    init = "\n".join("        rom[%d] = 30'd%d;" % (k, v) for k, v in enumerate(rom))
    src = f"""`timescale 1ns/1ps
// ============================================================================
// mesprit_asin_lut  --  AUTO-GENERATED by scripts/gen_luts.py, do not edit.
//
// theta = asin(u) for u in Q1.30 (|u| <= 2^30), theta in Q28 radians.
// Coarse table: 1024 segments over [0,1]; fine table: 1024 segments over
// [1-1/32, 1]. Linear interpolation, odd symmetry for negative u.
// Both tables share one 2048 x 30 dual-port ROM (block RAM).
// Four-cycle latency (ROM read, slope, multiply, add), fully pipelined.
// Max error 0.12 deg at |u| -> 1 (end-fire), < 0.0005 deg for |u| < 0.99.
// ============================================================================
module mesprit_asin_lut (
    input  wire               clk,
    input  wire               rst,
    input  wire               valid_in,
    input  wire signed [31:0] u_q30,       // must satisfy |u| <= 2^30
    output reg  signed [31:0] theta_q28,
    output reg                valid_out
);

    localparam [30:0] ONE       = 31'h4000_0000;
    localparam [30:0] FINE_BASE = 31'h3E00_0000;   // 1 - 1/32
    localparam [29:0] HALF_PI   = 30'd{fine[-1]};

    (* rom_style = "block" *) reg [29:0] rom [0:2047];

    initial begin
{init}
    end

    // |u| clamped to 1.0
    wire        neg   = u_q30[31];
    wire [31:0] u_abs = neg ? (~u_q30 + 32'd1) : u_q30;
    wire [30:0] ua    = (u_abs >= {{1'b0, ONE}}) ? ONE : u_abs[30:0];
    wire        fine  = (ua >= FINE_BASE);
    wire        one   = (ua == ONE);

    // coarse: segment = ua[30:20], fraction = ua[19:0]
    // fine  : (ua - FINE_BASE) spans 2^25 -> segment = [24:15], fraction = [14:0]
    wire [30:0] uf    = ua - FINE_BASE;
    wire [10:0] addr0 = fine ? (11'd1023 + {{1'b0, uf[24:15]}}) : ua[30:20];
    wire [10:0] addr1 = addr0 + 11'd1;
    wire [19:0] frac  = fine ? {{uf[14:0], 5'd0}} : ua[19:0];

    reg  [29:0] t0, t1;
    reg  [19:0] frac_r, frac2;
    reg         neg_r, one_r, v1;
    reg  [29:0] base2, diff2, base3;
    reg         neg2, one2, v2, neg3, one3, v3;
    reg  [49:0] dlt3;

    // stage 1: dual-port synchronous ROM read (no reset -> block RAM)
    always @(posedge clk) begin
        t0 <= rom[addr0];
        t1 <= rom[addr1];
    end

    wire signed [31:0] mag4 = $signed({{2'b00, base3}}) + $signed({{2'b00, dlt3[49:20]}});

    always @(posedge clk) begin
        if (rst) begin
            v1 <= 1'b0; v2 <= 1'b0; v3 <= 1'b0;
            valid_out <= 1'b0;
            theta_q28 <= 32'sd0;
            frac_r <= 20'd0; neg_r <= 1'b0; one_r <= 1'b0;
            base2 <= 30'd0; diff2 <= 30'd0; frac2 <= 20'd0; neg2 <= 1'b0; one2 <= 1'b0;
            base3 <= 30'd0; dlt3 <= 50'd0; neg3 <= 1'b0; one3 <= 1'b0;
        end else begin
            v1     <= valid_in;
            frac_r <= frac;
            neg_r  <= neg;
            one_r  <= one;
            // stage 2: segment slope (asin is monotonic, t1 >= t0)
            v2    <= v1;
            base2 <= t0;
            diff2 <= t1 - t0;
            frac2 <= frac_r;
            neg2  <= neg_r;
            one2  <= one_r;
            // stage 3: slope * fraction
            v3    <= v2;
            base3 <= base2;
            dlt3  <= diff2 * frac2;
            neg3  <= neg2;
            one3  <= one2;
            // stage 4: add, sign
            valid_out <= v3;
            if (v3)
                theta_q28 <= one3 ? (neg3 ? -$signed({{2'b00, HALF_PI}}) : $signed({{2'b00, HALF_PI}}))
                                  : (neg3 ? -mag4 : mag4);
        end
    end

endmodule
"""
    with open(path, "w") as f:
        f.write(src)
    print("wrote", path)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "mesprit_asin_lut.v")
