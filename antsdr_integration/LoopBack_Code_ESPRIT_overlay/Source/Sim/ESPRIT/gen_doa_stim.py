#!/usr/bin/env python3
"""
gen_doa_stim.py -- stimulus + expected results for tb_gnss_doa.v

Generates two-channel AD9361-format RX samples (12-bit, right-aligned,
sign-extended into 16 bits) for a single far-field source per window, and the
DOA each estimator must report for every window, computed with the reference
equations of Li et al., IEEE TIM 2025 (fourth-order cumulant, C^p, closed
forms for M = 2).

Outputs (written next to this script unless a directory is given):
  doa_stim.hex         one line per snapshot: {Q1,I1,Q0,I0} 16-bit hex each
  doa_tb_expected.vh   Verilog include with the expected angles and the
                       test-generator sweep table

The pre-generated files are committed, so Python is only needed to change the
test vectors:   python3 gen_doa_stim.py [out_dir]
"""
import math
import os
import sys

import numpy as np

LOG2_SNAP = 10                  # window used by the live-RX test
P = 4                           # C^p
MU = 1024 / 2.0 ** 30
K = 1.0 / math.pi               # d = lambda/2
THETAS_LIVE = [-50.0, -20.0, 0.0, 15.0, 40.0, 65.0]
KINDS = ["tone", "qpsk", "chirp", "tone", "qpsk", "tone"]
SNR_DB = 15.0
AMP = 0.35                      # of 12-bit full scale
TG_THETAS = [-60.0, -30.0, -10.0, 0.0, 10.0, 30.0, 45.0, 60.0]


def cumulant_matrix(X):
    T = X.shape[1]
    x0 = X[0]
    R = X @ X.conj().T / T
    Pm = (X * x0).mean(axis=1)
    M4 = (X * np.abs(x0) ** 2) @ X.conj().T / T
    return M4 - np.outer(R[:, 0], R[0, :]) - np.outer(Pm, Pm.conj()) - R * R[0, 0]


def bfp(a, d, b):
    m = max(abs(a), abs(d), abs(b.real), abs(b.imag))
    if m == 0:
        return a, d, b
    s = 2.0 ** (math.floor(math.log2(m)) + 1)
    return a / s, d / s, b / s


def cpow(C, p):
    a, d, b = bfp(C[0, 0].real, C[1, 1].real, C[0, 1])
    for _ in range(int(math.log2(p))):
        a, d, b = bfp(a * a + abs(b) ** 2, d * d + abs(b) ** 2, (a + d) * b)
    return a, d, b


def iuesprit(C):
    a, d, b = cpow(C, P)
    A = 0.5 * (a + d)
    r = np.array([A + b.real, b.imag])
    s = -np.array([b.imag, A - b.real])
    phi = 2.0 * math.atan2(r @ s, r @ r + MU)
    return math.degrees(math.asin(max(-1.0, min(1.0, -K * phi))))


def mesprit(C):
    a, d, b = cpow(C, P)
    psi = (a + d) * np.conj(b) / (a * a + abs(b) ** 2 + MU)
    phi = math.atan2(psi.imag, psi.real)
    return math.degrees(math.asin(max(-1.0, min(1.0, -K * phi)))), abs(psi)


def window(theta, kind, rng, T):
    a = np.exp(-1j * math.pi * np.arange(2) * math.sin(math.radians(theta)))
    n = np.arange(T)
    if kind == "tone":
        s = np.exp(1j * (2 * math.pi * 0.0213 * n + rng.uniform(0, 2 * math.pi)))
    elif kind == "qpsk":
        s = np.exp(1j * (math.pi / 4 + math.pi / 2 * rng.integers(0, 4, T)))
    else:
        s = np.exp(1j * math.pi * 2e-4 * n ** 2)
    X = AMP * np.outer(a, s)
    npow = AMP ** 2 / 10 ** (SNR_DB / 10)
    X += math.sqrt(npow / 2) * (rng.standard_normal((2, T)) + 1j * rng.standard_normal((2, T)))
    I = np.clip(np.round(X.real * 2048), -2048, 2047).astype(int)
    Q = np.clip(np.round(X.imag * 2048), -2048, 2047).astype(int)
    return I, Q


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
    rng = np.random.default_rng(2026)
    T = 1 << LOG2_SNAP
    lines, exp_i, exp_m, exp_mag = [], [], [], []
    for th, kind in zip(THETAS_LIVE, KINDS):
        I, Q = window(th, kind, rng, T)
        for k in range(T):
            w = [Q[1, k], I[1, k], Q[0, k], I[0, k]]
            lines.append("".join("%04x" % (v & 0xFFFF) for v in w))
        Xq = (I + 1j * Q) / 2048.0          # == Q1.15 value of {x[11:0],4'b0}
        C = cumulant_matrix(Xq)
        exp_i.append(iuesprit(C))
        dm, mag = mesprit(C)
        exp_m.append(dm)
        exp_mag.append(mag)
    with open(os.path.join(out, "doa_stim.hex"), "w") as f:
        f.write("\n".join(lines) + "\n")

    with open(os.path.join(out, "doa_tb_expected.vh"), "w") as f:
        f.write("// GENERATED by gen_doa_stim.py -- do not edit\n")
        f.write("localparam integer LIVE_LOG2_SNAP = %d;\n" % LOG2_SNAP)
        f.write("localparam integer LIVE_WINDOWS   = %d;\n" % len(THETAS_LIVE))
        f.write("localparam integer TG_POINTS      = %d;\n" % len(TG_THETAS))
        f.write("task load_expected;\n  begin\n")
        for k, (th, ei, em, mg) in enumerate(zip(THETAS_LIVE, exp_i, exp_m, exp_mag)):
            f.write("    live_true[%d] = %.6f; live_exp_i[%d] = %.6f; live_exp_m[%d] = %.6f; live_exp_mag[%d] = %.6f;\n"
                    % (k, th, k, ei, k, em, k, mg))
        for k, th in enumerate(TG_THETAS):
            # dphi = -pi*sin(theta)  ->  DPHASE = dphi/(2 pi) * 2^32 = -sin(theta)/2 * 2^32
            dph = int(round(-math.sin(math.radians(th)) / 2.0 * 2 ** 32)) & 0xFFFFFFFF
            f.write("    tg_theta[%d] = %.6f; tg_dphase[%d] = 32'h%08x;\n" % (k, th, k, dph))
        f.write("  end\nendtask\n")
    print("wrote %d snapshots, %d live windows, %d test-generator points to %s"
          % (len(lines), len(THETAS_LIVE), len(TG_THETAS), out))
    for th, ei, em, mg in zip(THETAS_LIVE, exp_i, exp_m, exp_mag):
        print("  true %6.1f  I-UESPRIT %8.4f  M-ESPRIT %8.4f  |psi| %.4f" % (th, ei, em, mg))


if __name__ == "__main__":
    main()
