// ============================================================================
//  doa_test_gen.v
//  ANTSDR E310 V1 / GNSS CRPA project -- ESPRIT DOA integration
// ----------------------------------------------------------------------------
//  Built-in two-channel test source for verifying the DOA chain ON HARDWARE
//  without antennas, RF cables or a signal generator.
//
//  It synthesises the snapshot a two-element array would see from a single
//  far-field narrow-band source:
//
//      x0[n] = A * exp(j*p[n])            + w0[n]
//      x1[n] = A * exp(j*(p[n] + dphi))   + w1[n]
//
//      p[n+1] = p[n] + FTW                (32-bit phase accumulator)
//      dphi   = 2*pi * DPHASE / 2^32      (inter-element phase)
//
//  For a ULA with spacing d (Eq. (2) of Li et al.):  dphi = -2*pi*d*sin(theta)/lambda
//  so a known DPHASE gives a known expected angle:
//      theta_expected = asin( -k * dphi ),   k = lambda/(2*pi*d)
//  (k = 1/pi for d = lambda/2  ->  theta = asin(-2*DPHASE/2^32)).
//
//  A        : 30000 >> amp_shift            (full scale is 32767)
//  w0, w1   : optional near-Gaussian noise (sum of two uniform 16-bit
//             xorshift32 words per component) scaled by >> noise_shift
//
//  Output rate: one snapshot every `div` clocks (div is clamped to >= 8; the
//  four sine/cosine look-ups share one block-RAM port, 8-cycle sequence).
//  Original work for this project.
// ============================================================================

