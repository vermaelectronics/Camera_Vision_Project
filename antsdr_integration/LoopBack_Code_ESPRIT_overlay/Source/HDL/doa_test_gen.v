  wire signed [16:0] n0i = noise_en ? (tri16(lf0) >>> noise_shift) : 17'sd0;
  wire signed [16:0] n0q = noise_en ? (tri16(lf1) >>> noise_shift) : 17'sd0;
  wire signed [16:0] n1i = noise_en ? (tri16(lf2) >>> noise_shift) : 17'sd0;
  wire signed [16:0] n1q = noise_en ? (tri16(lf3) >>> noise_shift) : 17'sd0;

  always @(posedge clk) begin
    if (rst || !en) begin
      cnt   <= 16'd0;
      phase <= 32'd0;
      step  <= 3'd0;
      valid <= 1'b0;
      raddr <= 10'd0;
      p0 <= 32'd0; p1 <= 32'd0;
      c0 <= 16'sd0; s0 <= 16'sd0; c1 <= 16'sd0; s1 <= 16'sd0;
      x0_i <= 16'sd0; x0_q <= 16'sd0; x1_i <= 16'sd0; x1_q <= 16'sd0;
    end else begin
      valid <= 1'b0;
      cnt   <= (cnt >= div_c - 1'b1) ? 16'd0 : cnt + 1'b1;

      // look-up sequence: addr issued at step k, data available at step k+1
      case (step)
        3'd0: if (cnt == 16'd0) begin
                p0    <= phase;
                p1    <= phase + dphase;
                phase <= phase + ftw;
                step  <= 3'd1;
              end
        3'd1: begin raddr <= (p0 + QUARTER) >> 22;                 step <= 3'd2; end
        3'd2: begin raddr <=  p0            >> 22;                 step <= 3'd3; end
        3'd3: begin raddr <= (p1 + QUARTER) >> 22; c0 <= rdata;    step <= 3'd4; end
        3'd4: begin raddr <=  p1            >> 22; s0 <= rdata;    step <= 3'd5; end
        3'd5: begin                                c1 <= rdata;    step <= 3'd6; end
        3'd6: begin
                s1 <= rdata;
                step <= 3'd7;
              end
        default: begin
                x0_i  <= sat16((c0 >>> amp_shift) + n0i);
                x0_q  <= sat16((s0 >>> amp_shift) + n0q);
                x1_i  <= sat16((c1 >>> amp_shift) + n1i);
                x1_q  <= sat16((s1 >>> amp_shift) + n1q);
                valid <= 1'b1;
                lf0 <= xs32(lf0); lf1 <= xs32(lf1);
                lf2 <= xs32(lf2); lf3 <= xs32(lf3);
                step <= 3'd0;
              end
      endcase
    end
  end

endmodule
