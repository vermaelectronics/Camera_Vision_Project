#!/usr/bin/env python3
"""Generate Source/HDL/sfap_win_rom.v: sqrt-Hann window w[m] = sin(pi m / 2048), m = 0..2047, Q0.16 unsigned (1.0 -> 65535).
The 2048-point transform reads w[n]; the 1024-point one reads every second entry (sin(pi n / 1024) = w[2n])."""
import math, sys
out = sys.argv[1] if len(sys.argv) > 1 else "Source/HDL/sfap_win_rom.v"
with open(out, "w") as f:
    f.write("// Generated by Tests/sfap/gen_window.py. sqrt-Hann window sin(pi m/2048), 2048 entries, Q0.16 unsigned. Two read ports.\n")
    f.write("module sfap_win_rom (input wire clk, input wire [10:0] a, output reg [15:0] d, input wire [10:0] b, output reg [15:0] e);\n")
    f.write("  (* rom_style = \"block\" *) reg [15:0] mem [0:2047];\n  initial begin\n")
    for n in range(2048):
        f.write(f"    mem[{n}] = 16'd{min(65535, round(math.sin(math.pi * n / 2048) * 65536))};\n")
    f.write("  end\n  reg [15:0] e0;                                   // port b has BRAM output register + a fabric register (latency 2)\n  always @(posedge clk) begin d <= mem[a]; e0 <= mem[b]; e <= e0; end\nendmodule\n")
