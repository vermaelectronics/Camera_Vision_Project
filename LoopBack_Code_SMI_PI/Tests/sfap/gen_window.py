#!/usr/bin/env python3
"""Generate Source/HDL/sfap_win_rom.v: sqrt-Hann window w[n] = sin(pi n / 1024), Q0.16 unsigned (1.0 -> 65535)."""
import math, sys
out = sys.argv[1] if len(sys.argv) > 1 else "Source/HDL/sfap_win_rom.v"
with open(out, "w") as f:
    f.write("// Generated by Tests/sfap/gen_window.py. sqrt-Hann window, 1024 entries, Q0.16 unsigned. Two read ports.\n")
    f.write("module sfap_win_rom (input wire clk, input wire [9:0] a, output reg [15:0] d, input wire [9:0] b, output reg [15:0] e);\n")
    f.write("  (* rom_style = \"block\" *) reg [15:0] mem [0:1023];\n  initial begin\n")
    for n in range(1024):
        f.write(f"    mem[{n}] = 16'd{min(65535, round(math.sin(math.pi * n / 1024) * 65536))};\n")
    f.write("  end\n  always @(posedge clk) begin d <= mem[a]; e <= mem[b]; end\nendmodule\n")
