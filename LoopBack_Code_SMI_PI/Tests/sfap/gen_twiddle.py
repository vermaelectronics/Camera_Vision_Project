#!/usr/bin/env python3
"""Generate Source/HDL/sfap_twiddle.v: ROMs of W_M^e = cos - j sin, M = 16, 64, 256, 1024.
Q1.16 signed 18-bit: +1.0 is stored as 65535 (0x0FFFF)."""
import math, sys
out = sys.argv[1]
TW = 18; ONE = (1 << 16) - 1
def rom(M, n=None):
    L = []
    for e in range(n or M):
        c = round(math.cos(2 * math.pi * e / M) * ONE)
        s = round(-math.sin(2 * math.pi * e / M) * ONE)      # W = cos - j sin  -> store (cos, -sin)
        L.append((c & ((1 << TW) - 1), s & ((1 << TW) - 1)))
    return L
with open(out, "w") as f:
    f.write("// Generated by Tests/sfap/gen_twiddle.py. Do not edit.\n")
    f.write("// sfap_tw_rom_<M>: {cos, -sin} of 2*pi*e/M, signed 18 bit, Q1.16 (+1.0 = 65535). One clock read.\n")
    for M, n in ((16, 16), (64, 64), (256, 256), (1024, 1024), (2048, 1024)):   # 2048: half circle only (radix-2 stage of the 2048-point FFT)
        aw = int(math.log2(n))
        f.write(f"module sfap_tw_rom_{M} (input wire clk, input wire [{aw-1}:0] a, output reg [35:0] d);\n")
        f.write(f"  (* rom_style = \"{'block' if n >= 1024 else 'distributed'}\" *) reg [35:0] mem [0:{n-1}];\n")
        f.write("  initial begin\n")
        for e, (c, s) in enumerate(rom(M, n)):
            f.write(f"    mem[{e}] = 36'h{((c << 18) | s):09X};\n")
        f.write("  end\n  always @(posedge clk) d <= mem[a];\nendmodule\n\n")
