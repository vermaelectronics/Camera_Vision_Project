#!/usr/bin/env python3
exec(open(__file__).read().split("#---")[0]) if False else None
import math, sys
L = [min(1 << 17, round((1 << 17) / (1.0 + (a + 0.5) / 512.0))) for a in range(512)]
out = sys.argv[1] if len(sys.argv) > 1 else "Source/HDL/sfap_recip_rom.v"
with open(out, "w") as f:
    f.write("// Generated by Tests/sfap/gen_recip.py. 1/m, m in [1,2): 512 entries, Q1.17.\n")
    f.write("module sfap_recip_rom (input wire clk, input wire [8:0] a, output reg [17:0] d);\n")
    f.write("  (* rom_style = \"distributed\" *) reg [17:0] mem [0:511];\n  initial begin\n")
    for i, v in enumerate(L):
        f.write(f"    mem[{i}] = 18'd{v};\n")
    f.write("  end\n  always @(posedge clk) d <= mem[a];\nendmodule\n")
